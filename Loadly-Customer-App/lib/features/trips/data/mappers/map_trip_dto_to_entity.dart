import '../../domain/entities/destination.dart';
import '../../domain/entities/trip.dart';
import '../models/trip_dto.dart';

Trip mapTripDtoToEntity(TripDto dto) {
  return Trip(
    id: dto.id,
    contractId: dto.contractId,
    contractDestinationId: dto.contractDestinationId,
    vehicleTypeId: dto.vehicleTypeId,
    vehicleId: dto.vehicleId,
    driverId: dto.driverId,
    startDate: dto.startDate,
    endDate: dto.endDate,
    status: dto.status,
    contractDistanceKm: dto.contractDistanceKm,
    actualDistanceKm: dto.actualDistanceKm,
    numberOfDays: dto.numberOfDays,
    totalAddonsCost: dto.totalAddonsCost,
    totalTripCost: dto.totalTripCost,
    tripCostWithoutAddon: dto.tripCostWithoutAddon,
    contractVehicleTypeId: dto.contractVehicleTypeId,
    isExtraTrip: dto.isExtraTrip,
    isDailyExtraTrip: dto.isDailyExtraTrip,
    contactPersonName: dto.contactPersonName,
    contactPersonMobile: dto.contactPersonMobile,
    helpersCount: dto.helpersCount,
    actualCargoWeightTons: dto.actualCargoWeightTons,
    cargoPrice: dto.cargoPrice,
    currentDriverStatus: dto.currentDriverStatus,
    currentDriverStatusName: dto.currentDriverStatusName,
    cutoffDuration: dto.cutoffDuration,
    referenceNumber: dto.referenceNumber,
    spotPrice: dto.spotPrice,
    tripDocumentStatus: dto.tripDocumentStatus,
    tripDocumentStatusName: dto.tripDocumentStatusName,
    tripStatusName: dto.tripStatusName,
    contractDestination: Destination(
      description: dto.contractDestination?.description,
      end: End(
        addressName: dto.contractDestination?.end?.addressName,
        googlePlaceId: dto.contractDestination?.end?.googlePlaceId,
        id: dto.contractDestination?.end?.id,
        latitude: dto.contractDestination?.end?.latitude,
        longitude: dto.contractDestination?.end?.longitude,
      ),
      start: Start(
        addressName: dto.contractDestination?.start?.addressName,
        googlePlaceId: dto.contractDestination?.start?.googlePlaceId,
        id: dto.contractDestination?.start?.id,
        latitude: dto.contractDestination?.start?.latitude,
        longitude: dto.contractDestination?.start?.longitude,
      ),
      expectedKms: dto.contractDestination?.expectedKms,
      id: dto.id,
      nameAr: dto.contractDestination?.nameAr,
      nameEn: dto.contractDestination?.nameEn,
      numberOfDays: dto.contractDestination?.numberOfDays,
      contractId: dto.contractDestination?.contractId,
      fixedTripPrice: dto.contractDestination?.fixedTripPrice,
      pricePerTon: dto.contractDestination?.pricePerTon,
      status: dto.contractDestination?.status,
      statusName: dto.contractDestination?.statusName,
    ),
    driver: Driver(
      id: dto.driver?.id,
      nationalId: dto.driver?.nationalId,
      email: dto.driver?.email,
      fullName: dto.driver?.fullName,
      fullNameEn: dto.driver?.fullNameEn,
      fullNameAr: dto.driver?.fullNameAr,
      phone: dto.driver?.phone,
    ),
    contract: Contract(
      id: dto.contract?.id,
      nameAr: dto.contract?.nameAr,
      nameEn: dto.contract?.nameEn,
      referenceNumber: dto.contract?.referenceNumber,
    ),
    contractVehicleType: ContractVehicleType(
      addedBy: dto.contractVehicleType?.addedBy,
      autoAssignMode: dto.contractVehicleType?.autoAssignMode,
      consumptionRate: dto.contractVehicleType?.consumptionRate,
      contractId: dto.contractVehicleType?.contractId,
      dailyValue: dto.contractVehicleType?.dailyValue,
      id: dto.contractVehicleType?.id,
      maxKms: dto.contractVehicleType?.maxKms,
      minCapacity: dto.contractVehicleType?.minCapacity,
      overCapacity: dto.contractVehicleType?.overCapacity,
      overConsumption: dto.contractVehicleType?.overConsumption,
      quantity: dto.contractVehicleType?.quantity,
      tripsPerDay: dto.contractVehicleType?.tripsPerDay,
      tripsPerMonth: dto.contractVehicleType?.tripsPerMonth,
      vehicleType: VehicleType(
        id: dto.contractVehicleType?.vehicleType?.id,
        nameAr: dto.contractVehicleType?.vehicleType?.nameAr,
        nameEn: dto.contractVehicleType?.vehicleType?.nameEn,
      ),
      vehicleTypeId: dto.contractVehicleType?.vehicleTypeId,
    ),
    vehicle: Vehicle(
      brandName: dto.vehicle?.brandName,
      chassisNumber: dto.vehicle?.chassisNumber,
      driver: Driver(
        id: dto.vehicle?.driver?.id,
        nationalId: dto.vehicle?.driver?.nationalId,
        email: dto.vehicle?.driver?.email,
        fullName: dto.vehicle?.driver?.fullName,
        fullNameEn: dto.vehicle?.driver?.fullNameEn,
        fullNameAr: dto.vehicle?.driver?.fullNameAr,
        phone: dto.vehicle?.driver?.phone,
      ),
      id: dto.vehicle?.id,
      modelName: dto.vehicle?.modelName,
      plateLetters: dto.vehicle?.plateLetters,
      plateNo: dto.vehicle?.plateNo,
      tailVehicles: dto.vehicle?.tailVehicles,
      vehicleType: VehicleType(
        id: dto.vehicle?.vehicleType?.id,
        nameAr: dto.vehicle?.vehicleType?.nameAr,
        nameEn: dto.vehicle?.vehicleType?.nameEn,
      ),
      vehicleTypeId: dto.vehicle?.vehicleTypeId,
      year: dto.vehicle?.year,
    ),
    company: Company(
      email: dto.company?.email,
      fullName: dto.company?.fullName,
      id: dto.company?.id,
      nameAr: dto.company?.nameAr,
      nameEn: dto.company?.nameEn,
      phone: dto.company?.phone,
      registrationNumber: dto.company?.registrationNumber,
    ),
    waypoints: dto.waypoints
        ?.map(
          (waypoint) => Waypoint(
            addressName: waypoint.addressName,
            googlePlaceId: waypoint.googlePlaceId,
            id: waypoint.id,
            latitude: waypoint.latitude,
            longitude: waypoint.longitude,
            sequence: waypoint.sequence,
            status: waypoint.status,
            stopType: waypoint.stopType,
            taskDetails: waypoint.taskDetails,
          ),
        )
        .toList(),
    recordings: dto.recordings
        ?.map(
          (recording) => Recording(
            addedBy: recording.addedBy,
            data: RecordingData(
              location: Location(
                accuracy: recording.data?.location?.accuracy,
                heading: recording.data?.location?.heading,
                latitude: recording.data?.location?.latitude,
                longitude: recording.data?.location?.longitude,
                speed: recording.data?.location?.speed,
                recordedAt: recording.data?.location?.recordedAt,
              ),
              note: recording.data?.note,

              waypoint: Waypoint(
                addressName: recording.data?.waypoint?.addressName,
                googlePlaceId: recording.data?.waypoint?.googlePlaceId,
                id: recording.data?.waypoint?.id,
                latitude: recording.data?.waypoint?.latitude,
                longitude: recording.data?.waypoint?.longitude,
                sequence: recording.data?.waypoint?.sequence,
                status: recording.data?.waypoint?.status,
                stopType: recording.data?.waypoint?.stopType,
                taskDetails: recording.data?.waypoint?.taskDetails,
              ),
            ),
            eventName: recording.eventName,
            eventType: recording.eventType,
            id: recording.id,
            createdAt: recording.createdAt,
          ),
        )
        .toList(),
    documents: dto.documents
        ?.map(
          (document) => Document(
            fileUrls: document.fileUrls,
            paths: document.paths,
            recordingId: document.recordingId,
            type: document.type,
            waypointId: document.waypointId,
          ),
        )
        .toList(),
    tripCharges: dto.tripCharges,
    currentLocation: dto.currentLocation,
    startLocation: StartLocation(
      latitude: dto.startLocation?.latitude,
      longitude: dto.startLocation?.longitude,
    ),
    invoice: dto.invoice,
  );
}
